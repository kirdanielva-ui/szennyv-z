"""Embed the original PDF family pages, without digitising their envelopes."""
from pathlib import Path
import base64
import hashlib
import json
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
PDF = ROOT / 'docs/flygt-n-3000-tartomanyok.pdf'
MODELS = ['3069','3085','3102','3127','3153','3171','3202','3301','3315','3231','3306','3312','3356','3400','3531','3800']
images = {}
with tempfile.TemporaryDirectory() as folder:
    for page, model in enumerate(MODELS, 6):
        output = Path(folder) / model
        subprocess.run(['pdftoppm', '-f', str(page), '-singlefile', '-scale-to', '1400', '-png', str(PDF), str(output)], check=True)
        images[model] = 'data:image/png;base64,' + base64.b64encode(output.with_suffix('.png').read_bytes()).decode('ascii')
source = {'file':'flygt-n-3000-tartomanyok.pdf','sha256':hashlib.sha256(PDF.read_bytes()).hexdigest(),'method':'Original PDF pages rendered as images; no numeric Q–H points inferred.'}
(ROOT / 'src/n-range-images.js').write_text('// Generated by scripts/extract_n_range_images.py. Original artwork, not sizing curves.\nexport const nRangeSource='+json.dumps(source,ensure_ascii=False)+';\nexport const nRangeImages='+json.dumps(images,separators=(',',':'))+';\n')
print(f'{len(images)} N-family pages embedded.')
