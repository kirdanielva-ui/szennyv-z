"""Import all numeric tables from the user's derived-curve PDF, without digitizing plots.

Requires pdftotext (Poppler). Not required for running the application or packaging.
The official catalogue URL is a reference, not a verified origin of these tables.
"""
from pathlib import Path
import hashlib
import json
import re
import subprocess

root = Path(__file__).resolve().parent.parent
pdf = root / 'docs' / 'flygt-szennyviz-szivattyugorbek.pdf'
text = subprocess.check_output(['pdftotext', '-layout', str(pdf), '-'], text=True)
records = []
for page_number, page in enumerate(text.split('\f'), 1):
    if 'Gyári teljesítménypontok' not in page:
        continue
    name = re.search(r'Flygt ([^\n]+)', page).group(1).strip()
    family = re.search(r'^(.+?) sorozat', page, re.M).group(1).strip()
    q = [float(v) for v in re.search(r'^Q \[l/s\]\s+(.+)$', page, re.M).group(1).split()]
    h = [float(v) for v in re.search(r'^H \[m\]\s+(.+)$', page, re.M).group(1).split()]
    if len(q) != len(h) or len(q) < 3 or q[0] != 0:
        raise ValueError(f'Invalid point table on page {page_number}')
    if any(q[i] <= q[i-1] or h[i] > h[i-1] for i in range(1, len(q))):
        raise ValueError(f'Unsupported non-monotonic table on page {page_number}')
    records.append({
        'id': re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-'),
        'model': name, 'family': family,
        'powerKw': float(re.search(r'P₂ = ([\d.]+)', page).group(1)),
        'pdfPage': page_number,
        'cataloguePage': int(re.search(r'Forrás: Flygt katalógus, (\d+)\.', page).group(1)),
        'qLps': q, 'headM': h,
    })
if len(records) != 30 or len({r['id'] for r in records}) != 30:
    raise ValueError('Expected exactly 30 distinct numeric pump tables')
source = {
    'title': 'Flygt szivattyúgörbék – gyári táblázatokból szerkesztett görbék',
    'pdfPath': '/docs/flygt-szennyviz-szivattyugorbek.pdf',
    'sha256': hashlib.sha256(pdf.read_bytes()).hexdigest(),
    'frequencyHz': 50,
    'originalCatalogueUrl': 'https://www.xylem.com/siteassets/brand/flygt/resources/manual/tech.cat_flygt-sx-sta-dl-dx-dxg_50hz_en.pdf',
    'verification': 'uploaded-numeric-tables-only',
    'originalCatalogueVerified': False,
    'method': 'numeric-table-transcription; piecewise-linear interpolation; Q[m³/h] = 3.6 × Q[L/s]',
    'precision': 'Original table precision retained; no plot digitization; interpolation is an approximation, not a tolerance guarantee.',
}
output = '// Generated by scripts/extract_curve_catalogue.py from the supplied PDF.\n'
output += '// These are derived table curves, not original manufacturer curve pages.\n'
output += 'export const catalogueSource = ' + json.dumps(source, ensure_ascii=False, indent=2) + ';\n'
output += 'export const catalogueTables = ' + json.dumps(records, ensure_ascii=False, indent=2) + ';\n'
(root / 'src' / 'pump-catalogue.js').write_text(output, encoding='utf-8')
print(f'Imported {len(records)} tables, {sum(len(r["qLps"]) for r in records)} Q–H points.')
