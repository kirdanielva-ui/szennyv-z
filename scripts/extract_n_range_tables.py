"""Read vector envelope boundaries from the supplied overview PDF, not pump curves.

Requires PyMuPDF only for regenerating this static data file. Neither the browser
nor the portable build depends on it. No Q=0 or single-valued pump curve is inferred.
"""
from pathlib import Path
import hashlib
import json
import math
import fitz

ROOT = Path(__file__).resolve().parent.parent
PDF = ROOT / 'docs/flygt-n-3000-tartomanyok.pdf'
MODELS = ['3069','3085','3102','3127','3153','3171','3202','3301','3315','3231','3306','3312','3356','3400','3531','3800']

def close_color(color, target):
    return color and all(abs(a-b)<0.002 for a,b in zip(color,target))

def calibration(pairs):
    assert len(pairs)>=2
    origin=min(pairs,key=lambda pair:pair[1])
    end=max(pairs,key=lambda pair:pair[1])
    scale=(end[1]-origin[1])/(end[0]-origin[0])
    assert all(abs(origin[1]+scale*(pixel-origin[0])-value)<0.001 for pixel,value in pairs)
    return lambda pixel:origin[1]+scale*(pixel-origin[0])

tables=[]
with fitz.open(PDF) as document:
    for page_number,model in enumerate(MODELS,6):
        page=document[page_number-1]
        assert f'Flygt N {model}' in page.get_text()
        drawings=page.get_drawings()
        grid=[d['rect'] for d in drawings if close_color(d.get('color'),(0.839216,0.890196,0.917647))]
        vertical=sorted({r.x0 for r in grid if r.width<0.001 and r.height>200})
        horizontal=sorted({r.y0 for r in grid if r.height<0.001 and r.width>300 and abs(r.x0-min(vertical))<0.001})
        assert len(vertical)>=3 and len(horizontal)>=3
        left,bottom=min(vertical),max(horizontal)
        q_pairs=[];h_pairs=[]
        for x0,y0,x1,y1,word,*_ in page.get_text('words'):
            try:value=float(word)
            except ValueError:continue
            if bottom+5<y0<bottom+18 and x0>left-5:
                nearest=min(vertical,key=lambda x:abs(x-(x0+x1)/2))
                assert abs(nearest-(x0+x1)/2)<0.1
                q_pairs.append((nearest,value))
            elif x1<left-5 and x0>left-40 and min(horizontal)-4<y0<bottom+3:
                nearest=min(horizontal,key=lambda y:abs(y-(y0+y1)/2))
                assert abs(nearest-(y0+y1)/2)<3
                h_pairs.append((nearest,value))
        q_value=calibration(q_pairs);h_value=calibration(h_pairs)
        envelopes=[d for d in drawings if close_color(d.get('fill'),(0.019608,0.466667,0.709804)) and len(d['items'])>8]
        assert len(envelopes)==1
        edges=[]
        for item in envelopes[0]['items']:
            assert item[0]=='l'
            a,b=item[1:]
            edges.append(((q_value(a.x),h_value(a.y)),(q_value(b.x),h_value(b.y))))
        qs=sorted({round(point[0],2) for edge in edges for point in edge})
        rows=[]
        for q in qs:
            # Vertex x coordinates are rounded to 0.01 L/s; intersect at their
            # original pixel-derived value, then round displayed envelope heights.
            raw=min((point[0] for edge in edges for point in edge),key=lambda raw:abs(raw-q))
            heights=[]
            for (qa,ha),(qb,hb) in edges:
                if min(qa,qb)-1e-5<=raw<=max(qa,qb)+1e-5:
                    if abs(qb-qa)<1e-5:heights.extend([ha,hb])
                    else:heights.append(ha+(hb-ha)*(raw-qa)/(qb-qa))
            assert len(heights)>=2
            rows.append({'qLps':q,'qM3h':round(q*3.6,3),'hMinM':round(min(heights),2),'hMaxM':round(max(heights),2)})
        assert all(math.isfinite(value) and value>=0 for row in rows for value in row.values())
        tables.append({'id':model,'pdfPage':page_number,'rows':rows})
source={'file':PDF.name,'sha256':hashlib.sha256(PDF.read_bytes()).hexdigest(),'method':'Vector envelope vertices calibrated against PDF axis ticks; vertical sections tabulated as lower/upper H. Rounded to 0.01 L/s and 0.01 m.','verification':'approximate-family-envelope-only','allowedForDutyCalculation':False}
(ROOT/'src/n-range-tables.js').write_text('// Generated by scripts/extract_n_range_tables.py. Approximate family ranges, NOT pump curves.\nexport const nRangeTableSource='+json.dumps(source,ensure_ascii=False,indent=2)+';\nexport const nRangeTables='+json.dumps(tables,ensure_ascii=False,indent=2)+';\n')
print(f'{len(tables)} family envelope tables, {sum(len(t["rows"]) for t in tables)} rows. Not used for duty calculations.')
